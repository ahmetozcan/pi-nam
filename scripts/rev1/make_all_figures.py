"""Stage 10: regenerate every manuscript figure in the shared style -> outputs/rev1/figures/.

All figures are drawn at their printed size (16 cm text width; include with
width=\\linewidth) with >= 8 pt text, as vector PDF plus 600-dpi PNG (R2-9). The SHM website
screenshot is a raster image and is copied unchanged. FIGURES.md maps each file to the
manuscript figure it replaces.

Inputs are the saved results of stage 1-8 (no model is re-trained).
Run from the repository root:  python3 scripts/rev1/make_all_figures.py
"""

import logging
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import data_audit  # noqa: E402
import fig_architecture  # noqa: E402
import fig_results  # noqa: E402
import plot_ablation  # noqa: E402
import run_stability  # noqa: E402
from src.feature_engineering import build_features  # noqa: E402

logger = logging.getLogger("make_all_figures")
OUT = ROOT / "outputs/rev1/figures"
SHM = ROOT.parent / "pinam_latex_submitted/figures/figure-04-shm-website.png"

# file stem -> (manuscript figure it replaces or adds, where it belongs)
MAPPING = [
    ("fig_shm_website.png", "figure-04-shm-website.png (unchanged screenshot)", "Sec. 1"),
    ("fig_variable_distributions", "new (R3-10, T10)", "Sec. 3, data"),
    ("fig_architecture", "figure-pinam-v1-architecture.pdf", "Sec. 4, model"),
    ("fig_main_comparison", "figure-01-main-comparison.pdf (+ replaces figure-02 MCC and "
     "figure-03 AUC trajectory)", "Sec. 5, results"),
    ("fig_ablation_steps", "new (stage 5, T35)", "Sec. 5, ablation"),
    ("fig_robustness", "new (R1, T42)", "Sec. 5, robustness"),
    ("fig_shapes_stability", "figure-pinam-v1-shapes.pdf (T43)", "Sec. 5, interpretation"),
    ("fig_factor_correlation", "new, supplementary only (R3-9)", "Supplementary"),
]


def write_mapping() -> None:
    lines = ["# Figures for the revised manuscript", "",
             "Generated by `scripts/rev1/make_all_figures.py`; drawn at 16 cm width, "
             "include with `width=\\linewidth`.", "",
             "| File | Replaces / adds | Place |", "|---|---|---|"]
    lines += [f"| `{f}` | {r} | {p} |" for f, r, p in MAPPING]
    (OUT / "FIGURES.md").write_text("\n".join(lines) + "\n")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    if SHM.exists():  # the screenshot ships with the manuscript sources, not with the code
        shutil.copy(SHM, OUT / "fig_shm_website.png")
    _, model = build_features(str(ROOT / "config.yaml"))
    data_audit.plot_distributions(model.reset_index(drop=True), OUT)
    fig_architecture.make(OUT)
    fig_results.make(OUT)
    plot_ablation.make(OUT)
    if all((run_stability.GRID / "states" / f"{s}.pt").exists()
           for s in run_stability.SOURCES.values()):
        run_stability.make_figures(OUT)
    else:  # the shape and correlation figures need the trained ensembles
        logger.info("skipped shape/correlation figures: model states not found "
                    "(run scripts/rev1/run_grid.py first)")
    write_mapping()
    logger.info("wrote %d files to %s", len(list(OUT.iterdir())), OUT)


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    for noisy in ("src.feature_engineering", "src.revision.info_sets"):
        logging.getLogger(noisy).setLevel(logging.WARNING)
    main()
